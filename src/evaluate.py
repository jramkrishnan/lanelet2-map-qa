"""Run the QA checks on every faulty map and score them against the ground truth.

Run with: python3 src/evaluate.py   (after inject_faults.py)
Writes outputs/eval.md and prints the same summary table.

How a trial is scored:
- Baseline: issues on the clean map are ignored in every trial (there are none today, but
  the comparison keeps the scoring honest if the clean map ever has a known issue).
- Caught by expected check: the check written for this fault type flagged the faulted primitive.
- Caught by any check: some check flagged the faulted primitive, even if it was a different one.
- False positive: a new issue on a primitive that is NOT the faulted one.
"""

import csv
from pathlib import Path

from checks import run_all_checks
from load_map import MAP_PATH, load_map

REPO_ROOT = Path(__file__).resolve().parent.parent
FAULTY_DIR = REPO_ROOT / "outputs" / "faulty"
GROUND_TRUTH_PATH = REPO_ROOT / "outputs" / "ground_truth.csv"
EVAL_PATH = REPO_ROOT / "outputs" / "eval.md"
NOTES_PATH = REPO_ROOT / "docs" / "eval_notes.md"  # hand-written explanation of misses


def run_checks(osm_path):
    lanelet_map, projector = load_map(osm_path)
    return run_all_checks(lanelet_map, projector, osm_path=osm_path)


def issue_key(issue):
    return (issue["check"], issue["primitive_id"])


def score_trial(truth, issues, baseline_keys):
    """Compare one faulty map's issues with its ground truth row."""
    target_id = int(truth["primitive_id"])
    new_issues = [i for i in issues if issue_key(i) not in baseline_keys]
    on_target = [i for i in new_issues if i["primitive_id"] == target_id]
    return {
        "trial_id": int(truth["trial_id"]),
        "fault_type": truth["fault_type"],
        "primitive_id": target_id,
        "detail": truth["detail"],
        "expected_check": truth["expected_check"],
        "caught_expected": any(i["check"] == truth["expected_check"] for i in on_target),
        "caught_any": len(on_target) > 0,
        "checks_on_target": sorted({i["check"] for i in on_target}),
        "false_positives": [i for i in new_issues if i["primitive_id"] != target_id],
    }


def summarize(results):
    """One row per fault type, plus a total row."""
    rows = []
    fault_types = sorted({r["fault_type"] for r in results})
    for fault_type in fault_types + ["ALL"]:
        group = [r for r in results if fault_type in ("ALL", r["fault_type"])]
        rows.append({
            "fault_type": fault_type,
            "trials": len(group),
            "caught_expected": sum(r["caught_expected"] for r in group),
            "caught_any": sum(r["caught_any"] for r in group),
            "false_positives": sum(len(r["false_positives"]) for r in group),
        })
    return rows


def pct(n, d):
    return f"{100 * n / d:.0f}%" if d else "n/a"


def format_report(results, summary, baseline_issues):
    lines = ["# Fault injection evaluation", ""]
    lines.append(f"Generated by `src/evaluate.py`. {len(results)} trials, one injected fault per "
                 f"copy of `map/annotations.osm`. Clean-map issues used as baseline: "
                 f"{len(baseline_issues)}.")
    lines.append("")
    lines.append("## Recall by fault type")
    lines.append("")
    lines.append("| Fault type | Trials | Caught by expected check | Caught by any check | False positives |")
    lines.append("|---|---|---|---|---|")
    for row in summary:
        name = "**All**" if row["fault_type"] == "ALL" else f"`{row['fault_type']}`"
        lines.append(
            f"| {name} | {row['trials']} "
            f"| {row['caught_expected']}/{row['trials']} ({pct(row['caught_expected'], row['trials'])}) "
            f"| {row['caught_any']}/{row['trials']} ({pct(row['caught_any'], row['trials'])}) "
            f"| {row['false_positives']} |"
        )
    lines.append("")
    lines.append("- **Caught by expected check:** the check written for that fault flagged the faulted primitive.")
    lines.append("- **Caught by any check:** at least one check flagged the faulted primitive.")
    lines.append("- **False positives:** new issues (not on the clean map) on a primitive other than the faulted one.")
    lines.append("")

    lines.append("## Every trial")
    lines.append("")
    lines.append("| Trial | Fault | Primitive | What was broken | Checks on faulted primitive | Other new issues |")
    lines.append("|---|---|---|---|---|---|")
    for r in results:
        on_target = ", ".join(r["checks_on_target"]) or "**none (missed)**"
        others = "; ".join(f"{i['check']} on {i['primitive_id']}" for i in r["false_positives"]) or "-"
        lines.append(f"| {r['trial_id']} | {r['fault_type']} | {r['primitive_id']} | {r['detail']} "
                     f"| {on_target} | {others} |")
    lines.append("")
    return "\n".join(lines)


def main():
    baseline_issues = run_checks(MAP_PATH)
    baseline_keys = {issue_key(i) for i in baseline_issues}

    with open(GROUND_TRUTH_PATH) as f:
        truth_rows = list(csv.DictReader(f))

    results = []
    for truth in truth_rows:
        osm_path = FAULTY_DIR / f"trial_{int(truth['trial_id']):02d}.osm"
        results.append(score_trial(truth, run_checks(osm_path), baseline_keys))

    summary = summarize(results)
    report = format_report(results, summary, baseline_issues) + "\n" + NOTES_PATH.read_text()
    EVAL_PATH.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
